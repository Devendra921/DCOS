type IconProps = HTMLAttributes<HTMLSpanElement> & {
  spin?: boolean;
  rotate?: number;
  twoToneColor?: string | [string, string];
};
function icon(Glyph: Icon, loading = false) {
  return forwardRef<HTMLSpanElement, IconProps>(function VwIcon({ spin, rotate, twoToneColor: _tone, className = '', style, ...props }, ref) {
    void _tone;
    return <span ref={ref} {...props} className={`vw-icon ${className}`} style={{ ...style, ...(rotate ? { transform: `rotate(${rotate}deg)` } : {}) }}>
      <Glyph weight="regular" size="1em" aria-hidden="true" focusable="false" className={spin || loading ? 'vw-icon-spin' : undefined} />
    </span>;
  });
}
